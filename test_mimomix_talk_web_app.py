"""Route and trust-boundary invariants for the v57 talking chat interface.

Pinned here:

1. The service refuses to exist without a real v57 checkpoint, and the checkpoint
   carries its own vocabulary.
2. Replies are generated by the model. Greedy mode uses MTP speculative decoding
   and is token-identical to plain greedy, so it is deterministic; sampling mode
   is explicitly labelled as not identical.
3. Nothing in a prompt selects a decoding mode, a budget, or a checkpoint --
   those come from typed fields, which are clamped rather than trusted.
4. Words outside the vocabulary are reported to the user instead of silently
   becoming `<unk>`.
"""

