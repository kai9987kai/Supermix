def test_routes_round_trip(client) -> None:
    assert client.get("/api/status").headers["Cache-Control"] == "no-store"
    chat = client.post("/api/chat", json={"message": "thanks", "max_new_tokens": 4})
    assert chat.status_code == 200
    assert "reply" in chat.get_json()
    assert client.post("/api/reset", json={"session_id": "default"}).status_code == 200
    assert client.get("/health").get_json()["status"] == "ok"


def test_bad_bodies_are_rejected(client) -> None:
    assert client.post("/api/chat", json=["nope"]).status_code == 400
    assert client.post("/api/chat", json={"message": ""}).status_code == 400
