def test_history_is_bounded(service: web.TalkService) -> None:
    for index in range(web.MAX_HISTORY_TURNS + 3):
        service.chat({"message": f"hello there {index}", "session_id": "bounded", "max_new_tokens": 3})
    assert len(service._sessions["bounded"]) <= web.MAX_HISTORY_TURNS


def test_reset_clears_only_its_own_session(service: web.TalkService) -> None:
    service.chat({"message": "thanks", "session_id": "keep", "max_new_tokens": 3})
    service.chat({"message": "thanks", "session_id": "drop", "max_new_tokens": 3})
    service.reset("drop")
    assert "drop" not in service._sessions
    assert service._sessions.get("keep")


