def test_greedy_replies_are_generated_and_deterministic(service: web.TalkService) -> None:
    first = service.chat({"message": "hello there", "session_id": "a", "max_new_tokens": 8})
    service.reset("a")
    second = service.chat({"message": "hello there", "session_id": "a", "max_new_tokens": 8})
    assert isinstance(first["reply"], str)
    assert first["reply"] == second["reply"], "greedy decoding must be deterministic"
    assert first["decoding"]["identical_to_plain_greedy"] is True
    assert first["tokens_generated"] <= 8


def test_sampling_is_labelled_as_not_greedy(service: web.TalkService) -> None:
    result = service.chat(
        {"message": "hello there", "mode": "sample", "max_new_tokens": 8, "seed": 3}
    )
    assert result["mode"] == "sample"
    assert result["decoding"]["identical_to_plain_greedy"] is False
    assert "temperature" in result["decoding"]


def test_sampling_with_a_seed_is_reproducible(service: web.TalkService) -> None:
    kwargs = {"message": "hello there", "mode": "sample", "max_new_tokens": 8, "seed": 11}
    service.reset("default")
    first = service.chat(dict(kwargs))
    service.reset("default")
    second = service.chat(dict(kwargs))
    assert first["reply"] == second["reply"]


def test_generation_reports_throughput(service: web.TalkService) -> None:
    result = service.chat({"message": "thanks", "max_new_tokens": 6})
    assert result["tokens_per_second"] > 0
    assert result["latency_ms"] > 0
    assert result["prompt_tokens"] > 0


def test_out_of_vocabulary_words_are_reported(service: web.TalkService) -> None:
    """The user is told what the model could not read, rather than left guessing."""

    result = service.chat({"message": "quantum chromodynamics", "max_new_tokens": 4})
    assert result["prompt_unknown_word_rate"] > 0
    assert result["warnings"] and "vocabulary" in result["warnings"][0]
    clean = service.chat({"message": "thanks", "max_new_tokens": 4})
    assert clean["warnings"] == []


